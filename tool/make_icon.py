#!/usr/bin/env python3
"""Generates SideDeck's app icon ("Two decks") for Android and iOS.

Two decks as stacked waveforms on black glass with the Sidekick-style cell
grid: deck A in bone, deck B in steel, kicks lit, and one orange bar line
with its marker running through both. Two tracks on the beat.

One shape list drives everything:
  - Android adaptive icon vector drawables (background, foreground, monochrome)
  - Android legacy PNGs (mipmap-*/ic_launcher.png, ic_launcher_round.png)
  - iOS AppIcon PNGs (opaque RGB, every size in the asset catalog)
  - the F-Droid / store listing icon (fastlane)

Standard library only (no PIL / numpy): a tiny rasterizer with exact
coverage for rectangles and supersampling for the marker and masks.

    python3 tool/make_icon.py
"""

import math
import os
import re
import struct
import zlib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

BLACK = (0x00, 0x00, 0x00)
GRID = (0x1C, 0x1D, 0x1F)
BONE = (0xE4, 0xE3, 0xDF)
STEEL = (0x98, 0x9F, 0xA5)
LIT = (0xFF, 0x6A, 0x21)

# Adaptive icon canvas is 108 x 108; launchers show the middle 72 and keep a
# 66-diameter circle safe. Everything below sits inside that circle.
CANVAS = 108.0
GRID_STEP = 9.0
GRID_WIDTH = 0.5


def deck_bars(center_y, color, seed):
    """13 bars on a 4-unit pitch around x = 54; every 4th one is a kick."""
    bars = []
    s = seed
    for k in range(-6, 7):
        s = (s * 9301 + 49297) % 233280
        kick = k % 4 == 0
        half = 9.0 if kick else 2.6 + (s / 233280.0) * 3.4
        x = 54.0 + 4.0 * k - 1.3
        bars.append(('rect', x, center_y - half, 2.6, 2 * half, color, 1.0 if kick else 0.55))
    return bars


def foreground_shapes():
    shapes = []
    shapes += deck_bars(44.0, BONE, 11)
    shapes += deck_bars(66.0, STEEL, 5)
    # The bar line: beat 1, through both decks, on the kicks.
    shapes.append(('rect', 52.6, 30.0, 2.8, 51.0, LIT, 1.0))
    shapes.append(('tri', (47.5, 26.0), (60.5, 26.0), (54.0, 33.0), LIT, 1.0))
    return shapes


def background_shapes():
    shapes = [('rect', 0.0, 0.0, CANVAS, CANVAS, BLACK, 1.0)]
    v = GRID_STEP
    while v < CANVAS:
        shapes.append(('rect', v - GRID_WIDTH / 2, 0.0, GRID_WIDTH, CANVAS, GRID, 1.0))
        shapes.append(('rect', 0.0, v - GRID_WIDTH / 2, CANVAS, GRID_WIDTH, GRID, 1.0))
        v += GRID_STEP
    return shapes


# ---------------------------------------------------------------- vectors

def hexcolor(c, alpha=1.0):
    return '#%02X%02X%02X%02X' % (round(alpha * 255), c[0], c[1], c[2])


def fmt(v):
    return ('%.2f' % v).rstrip('0').rstrip('.')


def path_of(shape):
    if shape[0] == 'rect':
        _, x, y, w, h = shape[:5]
        return 'M%s,%sh%sv%sh-%sz' % (fmt(x), fmt(y), fmt(w), fmt(h), fmt(w))
    _, a, b, c = shape[:4]
    return 'M%s,%sL%s,%sL%s,%sz' % (fmt(a[0]), fmt(a[1]), fmt(b[0]), fmt(b[1]), fmt(c[0]), fmt(c[1]))


def vector_xml(shapes, mono=False):
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        '<!-- Generated by tool/make_icon.py; edit the script, not this file. -->',
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        '    android:width="108dp"',
        '    android:height="108dp"',
        '    android:viewportWidth="108"',
        '    android:viewportHeight="108">',
    ]
    for s in shapes:
        color, alpha = s[-2], s[-1]
        fill = '#FFFFFFFF' if mono else hexcolor(color, alpha)
        lines.append('    <path android:fillColor="%s" android:pathData="%s" />' % (fill, path_of(s)))
    lines.append('</vector>')
    return '\n'.join(lines) + '\n'


# ------------------------------------------------------------- rasterizer

class Image:
    def __init__(self, size):
        self.size = size
        n = size * size
        self.r = [0.0] * n
        self.g = [0.0] * n
        self.b = [0.0] * n
        self.a = [0.0] * n

    def blend(self, i, color, cov):
        if cov <= 0.0:
            return
        if cov > 1.0:
            cov = 1.0
        inv = 1.0 - cov
        self.r[i] = self.r[i] * inv + color[0] * cov
        self.g[i] = self.g[i] * inv + color[1] * cov
        self.b[i] = self.b[i] * inv + color[2] * cov
        self.a[i] = self.a[i] * inv + cov


def overlap(p0, p1, q0, q1):
    return max(0.0, min(p1, q1) - max(p0, q0))


def draw(img, shapes, crop):
    """crop = (x0, y0, width) of the 108 canvas mapped onto the image."""
    cx0, cy0, cw = crop
    k = img.size / cw
    size = img.size
    for s in shapes:
        color, alpha = s[-2], s[-1]
        if s[0] == 'rect':
            _, x, y, w, h = s[:5]
            x0, x1 = (x - cx0) * k, (x + w - cx0) * k
            y0, y1 = (y - cy0) * k, (y + h - cy0) * k
            for py in range(max(0, int(math.floor(y0))), min(size, int(math.ceil(y1)))):
                cy = overlap(py, py + 1, y0, y1)
                if cy <= 0:
                    continue
                row = py * size
                for px in range(max(0, int(math.floor(x0))), min(size, int(math.ceil(x1)))):
                    cx = overlap(px, px + 1, x0, x1)
                    if cx > 0:
                        img.blend(row + px, color, cx * cy * alpha)
        else:
            _, a, b, c = s[:4]
            pts = [((p[0] - cx0) * k, (p[1] - cy0) * k) for p in (a, b, c)]
            minx = max(0, int(math.floor(min(p[0] for p in pts))))
            maxx = min(size, int(math.ceil(max(p[0] for p in pts))))
            miny = max(0, int(math.floor(min(p[1] for p in pts))))
            maxy = min(size, int(math.ceil(max(p[1] for p in pts))))

            def inside(x, y):
                d1 = (x - pts[1][0]) * (pts[0][1] - pts[1][1]) - (pts[0][0] - pts[1][0]) * (y - pts[1][1])
                d2 = (x - pts[2][0]) * (pts[1][1] - pts[2][1]) - (pts[1][0] - pts[2][0]) * (y - pts[2][1])
                d3 = (x - pts[0][0]) * (pts[2][1] - pts[0][1]) - (pts[2][0] - pts[0][0]) * (y - pts[0][1])
                neg = d1 < 0 or d2 < 0 or d3 < 0
                pos = d1 > 0 or d2 > 0 or d3 > 0
                return not (neg and pos)

            n = 4
            for py in range(miny, maxy):
                for px in range(minx, maxx):
                    hits = 0
                    for sy in range(n):
                        for sx in range(n):
                            if inside(px + (sx + 0.5) / n, py + (sy + 0.5) / n):
                                hits += 1
                    img.blend(py * size + px, color, hits / (n * n) * alpha)


def mask(img, kind):
    """Cuts the image to a circle or a rounded square (transparent outside)."""
    size = img.size
    rad = size / 2.0
    corner = size * 0.22

    def cover(x, y):
        if kind == 'circle':
            return (x - rad) ** 2 + (y - rad) ** 2 <= rad * rad
        qx = max(corner - x, 0, x - (size - corner))
        qy = max(corner - y, 0, y - (size - corner))
        return qx * qx + qy * qy <= corner * corner

    n = 4
    for py in range(size):
        for px in range(size):
            corners = [cover(px, py), cover(px + 1, py), cover(px, py + 1), cover(px + 1, py + 1)]
            if all(corners):
                continue
            hits = 0
            for sy in range(n):
                for sx in range(n):
                    if cover(px + (sx + 0.5) / n, py + (sy + 0.5) / n):
                        hits += 1
            i = py * size + px
            img.a[i] *= hits / (n * n)


def write_png(path, img, rgb=False):
    size = img.size
    rows = []
    for y in range(size):
        row = bytearray([0])
        for x in range(size):
            i = y * size + x
            a = img.a[i]
            if rgb:
                # Opaque: composite over black.
                row += bytes((round(min(255, img.r[i])), round(min(255, img.g[i])), round(min(255, img.b[i]))))
            else:
                if a > 0:
                    # Colours are premultiplied by the blend; undo for straight alpha.
                    r, g, b = (min(255, c / a) for c in (img.r[i], img.g[i], img.b[i]))
                else:
                    r = g = b = 0
                row += bytes((round(r), round(g), round(b), round(a * 255)))
        rows.append(bytes(row))
    raw = b''.join(rows)

    def chunk(tag, data):
        c = tag + data
        return struct.pack('>I', len(data)) + c + struct.pack('>I', zlib.crc32(c) & 0xFFFFFFFF)

    color_type = 2 if rgb else 6
    png = b'\x89PNG\r\n\x1a\n'
    png += chunk(b'IHDR', struct.pack('>IIBBBBB', size, size, 8, color_type, 0, 0, 0))
    png += chunk(b'IDAT', zlib.compress(raw, 9))
    png += chunk(b'IEND', b'')
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'wb') as f:
        f.write(png)


def render(size, crop, kind=None, rgb=False):
    img = Image(size)
    draw(img, background_shapes() + foreground_shapes(), crop)
    if kind:
        mask(img, kind)
    return img


# ----------------------------------------------------------------- outputs

def main():
    res = os.path.join(ROOT, 'android', 'app', 'src', 'main', 'res')
    drawable = os.path.join(res, 'drawable')
    with open(os.path.join(drawable, 'ic_launcher_background.xml'), 'w', newline='\n') as f:
        f.write(vector_xml(background_shapes()))
    with open(os.path.join(drawable, 'ic_launcher_foreground.xml'), 'w', newline='\n') as f:
        f.write(vector_xml(foreground_shapes()))
    with open(os.path.join(drawable, 'ic_launcher_monochrome.xml'), 'w', newline='\n') as f:
        f.write(vector_xml(foreground_shapes(), mono=True))

    # Legacy launcher PNGs: the visible middle 72 of the adaptive canvas.
    visible = (18.0, 18.0, 72.0)
    for density, size in (('mdpi', 48), ('hdpi', 72), ('xhdpi', 96), ('xxhdpi', 144), ('xxxhdpi', 192)):
        folder = os.path.join(res, 'mipmap-' + density)
        write_png(os.path.join(folder, 'ic_launcher.png'), render(size, visible, 'rounded'))
        write_png(os.path.join(folder, 'ic_launcher_round.png'), render(size, visible, 'circle'))

    # Store listing (F-Droid / fastlane): round, like before, at 512.
    write_png(os.path.join(ROOT, 'fastlane', 'metadata', 'android', 'en-US', 'images', 'icon.png'),
              render(512, visible, 'circle'))

    # iOS: every size in the asset catalog, opaque and full-bleed (iOS rounds
    # the corners itself). A slightly tighter crop than Android's mask.
    ios = os.path.join(ROOT, 'ios', 'Runner', 'Assets.xcassets', 'AppIcon.appiconset')
    tight = (16.0, 16.0, 76.0)
    for name in sorted(os.listdir(ios)):
        m = re.match(r'Icon-App-([\d.]+)x[\d.]+@(\d)x\.png$', name)
        if not m:
            continue
        size = int(round(float(m.group(1)) * int(m.group(2))))
        write_png(os.path.join(ios, name), render(size, tight, rgb=True), rgb=True)
        print('ios', name, size)
    print('done')


if __name__ == '__main__':
    main()
